export const strings: Record<Lang, Strings> = { en, ur }

export const LangContext = createContext<{ lang: Lang; t: Strings; setLang: (l: Lang) => void }>({
  lang: 'en',
  t: en,
  setLang: () => {},
})

export const useT = () => useContext(LangContext)

export function errText(e: unknown): string {
  return typeof e === 'string' ? e : e instanceof Error ? e.message : JSON.stringify(e)
}

export function formatDate(unix: number, lang: Lang): string {
  return new Date(unix * 1000).toLocaleString(lang === 'ur' ? 'ur-PK' : undefined, {
    dateStyle: 'medium',
    timeStyle: 'short',
  })
}
